// Regenerates supabase/seed.sql from src/data/demoVehicles.js.
// Usage: node scripts/gen-seed.mjs
import { writeFileSync } from 'node:fs';
import { demoVehicles } from '../src/data/demoVehicles.js';

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;

const rows = demoVehicles.map((v) =>
  `  (${[q(v.make), q(v.model), v.year, v.price ?? 'null', v.mileage ?? 'null', q(v.transmission), q(v.fuel_type),
    q(v.engine), q(v.colour), q(v.description), q(v.main_image), arr(v.images || []), q(v.status), v.featured,
    'true', `${q(v.created_at)}::timestamptz`].join(', ')})`,
);

const sql = `-- DEMO CONTENT — sample vehicles flagged is_demo = true.
-- Remove them any time with:  delete from public.vehicles where is_demo;
-- Generated by scripts/gen-seed.mjs — do not edit by hand.

insert into public.vehicles
  (make, model, year, price, mileage, transmission, fuel_type, engine, colour, description, main_image, images, status, featured, is_demo, created_at)
values
${rows.join(',\n')};
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote ${demoVehicles.length} demo vehicles to supabase/seed.sql`);
